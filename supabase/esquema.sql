-- Deuda de prestaciones ya realizadas, por plan (mismo cálculo que el respaldo en seguimiento/_lib/datos.ts)
create or replace view public.v_deuda_realizada with (security_invoker = true) as
with hechos as (
  select i.presupuesto_id, i.profesional_id,
         coalesce(i.precio_pactado, 0) as pactado,
         least(coalesce(i.abonado, 0), coalesce(i.precio_pactado, 0)) as pagado,
         greatest(coalesce(i.precio_pactado, 0) - coalesce(i.abonado, 0), 0) as saldo
  from public.presupuesto_items i
  where i.presupuesto_id is not null
    and (coalesce(i.progreso, 0) > 0
         or lower(trim(coalesce(i.estado, ''))) in ('realizado', 'atendido', 'terminado', 'finalizado', 'completado'))
    and lower(coalesce(i.estado, '')) not like '%cancel%'
    and lower(coalesce(i.estado, '')) not like '%anul%'
)
select p.id, p.paciente_id, p.nombre_tratamiento, p.especialista_id,
       sum(h.pactado) as realizado, sum(h.pagado) as pagado, sum(h.saldo) as saldo,
       coalesce(jsonb_agg(jsonb_build_object('profesional_id', h.profesional_id, 'saldo', h.saldo))
                filter (where h.saldo > 0), '[]'::jsonb) as items
from hechos h
join public.presupuestos p on p.id = h.presupuesto_id
where lower(coalesce(p.estado, '')) not like '%anul%'
group by p.id
having sum(h.saldo) >= 1000;

create or replace view public.vista_pacientes_morosos with (security_invoker = true) as
select pa.id, pa.nombre, pa.apellido, pa.rut, pa.telefono, sum(d.saldo) as saldo_pendiente
from public.v_deuda_realizada d
join public.pacientes pa on pa.id = d.paciente_id
group by pa.id;

-- ───────────────────────── FUNCIONES DE PAGOS ─────────────────────────

create or replace function public._recalcular_abonado_plan(p_presupuesto_id bigint)
returns void language sql security definer set search_path = public as $$
  update presupuestos
     set total_abonado = coalesce((select sum(abonado) from presupuesto_items where presupuesto_id = p_presupuesto_id), 0)
   where id = p_presupuesto_id;
$$;

-- Registra varias líneas de pago en una transacción: abona las prestaciones, suma los abonos libres
-- al saldo a favor y descuenta el saldo a favor usado. Devuelve los ids de los pagos creados.
create or replace function public.registrar_pago(p_lineas jsonb, p_saldo_usado numeric default 0)
returns bigint[] language plpgsql security definer set search_path = public as $$
declare
  l jsonb;
  v_id bigint;
  v_ids bigint[] := '{}';
  v_paciente bigint;
  v_item bigint;
  v_monto numeric;
  v_saldo numeric;
begin
  if auth.uid() is null then raise exception 'No autenticado'; end if;
  if jsonb_typeof(p_lineas) <> 'array' or jsonb_array_length(p_lineas) = 0 then
    raise exception 'No hay líneas de pago';
  end if;

  for l in select * from jsonb_array_elements(p_lineas) loop
    v_paciente := (l->>'paciente_id')::bigint;
    v_item := nullif(l->>'item_id', '')::bigint;
    v_monto := (l->>'monto')::numeric;
    if v_monto is null or v_monto <= 0 then raise exception 'Monto inválido'; end if;

    insert into pagos (paciente_id, monto, metodo_pago, numero_boleta, numero_referencia, profesional_id,
                       item_id, fecha_pago, comentario, nota, caja_id)
    values (v_paciente, v_monto, l->>'metodo_pago', l->>'numero_boleta', l->>'numero_referencia',
            nullif(l->>'profesional_id', '')::uuid, v_item, coalesce((l->>'fecha_pago')::timestamptz, now()),
            l->>'comentario', l->>'nota', nullif(l->>'caja_id', '')::bigint)
    returning id into v_id;
    v_ids := v_ids || v_id;

    if v_item is not null then
      update presupuesto_items set abonado = coalesce(abonado, 0) + v_monto where id = v_item;
      perform _recalcular_abonado_plan((select presupuesto_id from presupuesto_items where id = v_item));
    elsif coalesce(l->>'metodo_pago', '') <> 'Saldo a Favor' then
      update pacientes set saldo_a_favor = coalesce(saldo_a_favor, 0) + v_monto where id = v_paciente;
    end if;
  end loop;

  if coalesce(p_saldo_usado, 0) > 0 then
    select saldo_a_favor into v_saldo from pacientes where id = v_paciente for update;
    if coalesce(v_saldo, 0) < p_saldo_usado then raise exception 'Saldo a favor insuficiente'; end if;
    update pacientes set saldo_a_favor = saldo_a_favor - p_saldo_usado where id = v_paciente;
  end if;

  return v_ids;
end $$;

-- Pagos de prestaciones → quedan como abono libre y su monto pasa al saldo a favor.
-- Abonos libres → se anulan y se descuentan del saldo a favor.
create or replace function public.pasar_pagos_a_saldo(p_pago_ids text[], p_motivo text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  p record;
  v_paciente bigint;
  v_plan bigint;
begin
  if auth.uid() is null then raise exception 'No autenticado'; end if;

  for p in select * from pagos where id = any(p_pago_ids::bigint[]) and coalesce(estado, '') <> 'Anulado' for update loop
    v_paciente := p.paciente_id;
    if p.item_id is not null then
      select presupuesto_id into v_plan from presupuesto_items where id = p.item_id;
      update presupuesto_items set abonado = greatest(coalesce(abonado, 0) - p.monto, 0) where id = p.item_id;
      update pagos set item_id = null, motivo = p_motivo where id = p.id;
      update pacientes set saldo_a_favor = coalesce(saldo_a_favor, 0) + p.monto where id = p.paciente_id;
      perform _recalcular_abonado_plan(v_plan);
    else
      update pagos set estado = 'Anulado', anulado_por = auth.uid(), motivo = p_motivo where id = p.id;
      update pacientes set saldo_a_favor = coalesce(saldo_a_favor, 0) - p.monto where id = p.paciente_id;
    end if;
  end loop;

  return jsonb_build_object('saldo_nuevo', (select saldo_a_favor from pacientes where id = v_paciente));
end $$;

-- Cancela una prestación y pasa lo que se había pagado al saldo a favor del paciente
create or replace function public.cancelar_prestacion(p_item_id text, p_motivo text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_item presupuesto_items;
  v_paciente bigint;
  v_total numeric;
begin
  if auth.uid() is null then raise exception 'No autenticado'; end if;
  select * into v_item from presupuesto_items where id = p_item_id::bigint for update;
  if not found then raise exception 'Prestación no encontrada'; end if;
  select paciente_id into v_paciente from presupuestos where id = v_item.presupuesto_id;

  select coalesce(sum(monto), 0) into v_total
    from pagos where item_id = v_item.id and coalesce(estado, '') <> 'Anulado';

  update pagos set item_id = null, motivo = p_motivo
   where item_id = v_item.id and coalesce(estado, '') <> 'Anulado';
  if v_total > 0 then
    update pacientes set saldo_a_favor = coalesce(saldo_a_favor, 0) + v_total where id = v_paciente;
  end if;
  update presupuesto_items set estado = 'cancelada', abonado = 0 where id = v_item.id;
  perform _recalcular_abonado_plan(v_item.presupuesto_id);

  return jsonb_build_object('pasado_a_saldo', v_total);
end $$;

revoke execute on function public._recalcular_abonado_plan(bigint) from public, anon, authenticated;
revoke execute on function public.registrar_pago(jsonb, numeric) from public, anon;
revoke execute on function public.pasar_pagos_a_saldo(text[], text) from public, anon;
revoke execute on function public.cancelar_prestacion(text, text) from public, anon;
grant execute on function public.registrar_pago(jsonb, numeric) to authenticated;
grant execute on function public.pasar_pagos_a_saldo(text[], text) to authenticated;
grant execute on function public.cancelar_prestacion(text, text) to authenticated;

